import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const source=fs.readFileSync('src/core/agencias.ts','utf8');
const compiled=ts.transpile(source,{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022});
const {normalizarBanco,normalizarAgencia,localizarAgencias}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
assert.equal(normalizarBanco('1'),'001');
assert.equal(normalizarBanco('104'),'104');
assert.throws(()=>normalizarBanco('1234'));
assert.throws(()=>normalizarBanco('00a'));
assert.equal(normalizarAgencia('02816-0'),'2816');
assert.equal(normalizarAgencia('0001-X'),'1');
assert.throws(()=>normalizarAgencia('123456789'));
assert.throws(()=>normalizarAgencia('1/2'));
const rows=[{CodigoCompe:'00001',Endereco:'A'},{CodigoCompe:'00002',Endereco:'B'}];
assert.deepEqual(localizarAgencias(rows,'1'),[rows[0]]);
assert.deepEqual(localizarAgencias(rows,'3'),[]);
const index=JSON.parse(fs.readFileSync('public/dados/agencias/indice.json'));
assert.ok(index.totalFonte>1000);
assert.equal(new Set(index.bancos.map(bank=>bank.codigo)).size,index.bancos.length);
for(const bank of index.bancos){const payload=JSON.parse(fs.readFileSync(`public/dados/agencias/${bank.codigo}.json`));assert.equal(payload.banco.codigo,bank.codigo);assert.equal(payload.agencias.length,bank.agenciasNaBase);}
const caixa=JSON.parse(fs.readFileSync('public/dados/agencias/104.json'));
const sample=localizarAgencias(caixa.agencias,normalizarAgencia('2816'));
assert.equal(sample.length,1);
assert.equal(sample[0].Municipio,'BARRA VELHA');
assert.equal(sample[0].UF,'SC');
const bb=JSON.parse(fs.readFileSync('public/dados/agencias/001.json'));
assert.ok(bb.agencias.length>1000);
console.log(`Normalização, busca exata, ausências e integridade de ${index.bancos.length} arquivos de bancos aprovadas.`);
console.log('Amostra BCB: banco 104, agência 2816 → Barra Velha/SC.');
